"""
評価迷路 (seed 1000-1019) の恒久検証スクリプト
Permanent verification script for the evaluation mazes.

保存済みの npz (競技で実際に使われる保存物そのもの) を読み込み、教授指定の
5項目を検証する:
    (a) 連結性: 全256セルが (0,0) から BFS 到達可能
    (b) 中央2x2: 内壁4枚なし かつ ゴール区画から外部セルへの開口数 >= 1
    (c) スタート規定: h[0,1]==0, v[1,0]==1, h[0,0]==1, v[0,0]==1
    (d) 孤立柱ゼロ: 中央柱(8,8)以外の全柱に壁>=1枚接続。中央柱には壁0枚。
    (e) 再現性: EvalMazeGenerator.generate(seed) を再実行し npz と完全一致
加えて記録項目 (合否判定なし): 内部開通路数、スタート->ゴール最短セル距離、
ゴール開口数。

結果は表として print し、competition/mazes/eval/verification_report.json
に保存する。1件でも不合格なら exit code 1。

--write-log を付けると、VERIFICATION_LOG.md の「2. 案A適用後の検証」
セクションを本スクリプトの実行結果から機械的に生成し、書き込む(既存の
セクションはマーカー間の内容のみ置換され、手書きの「1. 生成器修正前の
検証」エントリ等はそのまま保持される)。

使い方 (Usage):
    .venv/bin/python competition/verify_eval_mazes.py
    .venv/bin/python competition/verify_eval_mazes.py --write-log
"""
import argparse
import datetime
import glob
import json
import os
import sys
from collections import deque

import numpy as np

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from competition.maze_gen import EvalMazeGenerator  # noqa: E402

MAZE_DIR = os.path.join(_REPO_ROOT, "competition", "mazes", "eval")
GOAL_CELLS = [(7, 7), (7, 8), (8, 7), (8, 8)]
CENTER_WALLS = [("v", 8, 7), ("v", 8, 8), ("h", 7, 8), ("h", 8, 8)]

LOG_PATH = os.path.join(_REPO_ROOT, "competition", "VERIFICATION_LOG.md")
LOG_SECTION_START = (
    "<!-- AUTO-GENERATED BY verify_eval_mazes.py --write-log (START) -->"
)
LOG_SECTION_END = "<!-- AUTO-GENERATED BY verify_eval_mazes.py --write-log (END) -->"


def _connects(v_walls, h_walls, x, y, nx, ny):
    """セル (x,y) と隣接セル (nx,ny) の間の壁が開いているか判定する。"""
    if (nx, ny) == (x + 1, y):
        return bool(v_walls[x + 1, y] == 0)
    if (nx, ny) == (x - 1, y):
        return bool(v_walls[x, y] == 0)
    if (nx, ny) == (x, y + 1):
        return bool(h_walls[x, y + 1] == 0)
    if (nx, ny) == (x, y - 1):
        return bool(h_walls[x, y] == 0)
    raise ValueError(f"({x},{y}) と ({nx},{ny}) は隣接していません")


def _neighbors(x, y):
    for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
        if 0 <= nx < 16 and 0 <= ny < 16:
            yield nx, ny


def bfs_reachable(v_walls, h_walls, start=(0, 0)):
    """start から到達可能な全セルの集合を返す (連結性検査 (a) 用)。"""
    visited = {start}
    q = deque([start])
    while q:
        x, y = q.popleft()
        for nx, ny in _neighbors(x, y):
            if (nx, ny) not in visited and _connects(v_walls, h_walls, x, y, nx, ny):
                visited.add((nx, ny))
                q.append((nx, ny))
    return visited


def bfs_distance(v_walls, h_walls, start, targets):
    """start から targets への最短セル距離のうち最小値を返す (記録項目用)。"""
    dist = {start: 0}
    q = deque([start])
    while q:
        x, y = q.popleft()
        d = dist[(x, y)]
        for nx, ny in _neighbors(x, y):
            if (nx, ny) not in dist and _connects(v_walls, h_walls, x, y, nx, ny):
                dist[(nx, ny)] = d + 1
                q.append((nx, ny))
    dists = [dist[t] for t in targets if t in dist]
    return min(dists) if dists else None


def post_connection_count(v_walls, h_walls, px, py):
    """柱 (px,py) に接続している壁の枚数を返す (孤立柱検査 (d) 用)。"""
    count = 0
    if py < 16 and v_walls[px, py] == 1:
        count += 1
    if py > 0 and v_walls[px, py - 1] == 1:
        count += 1
    if px < 16 and h_walls[px, py] == 1:
        count += 1
    if px > 0 and h_walls[px - 1, py] == 1:
        count += 1
    return count


def goal_opening_count(v_walls, h_walls):
    """ゴール区画 (中央2x2) から外部セルへの開口数を返す (記録項目 / (b) 用)。"""
    count = 0
    for gx, gy in GOAL_CELLS:
        for nx, ny in _neighbors(gx, gy):
            if (nx, ny) in GOAL_CELLS:
                continue
            if _connects(v_walls, h_walls, gx, gy, nx, ny):
                count += 1
    return count


def internal_open_passage_count(v_walls, h_walls):
    """内部(境界を除く)の開通路数を返す (記録項目用)。"""
    v_internal = v_walls[1:16, :]  # x = 1..15 (境界 x=0,16 を除く)
    h_internal = h_walls[:, 1:16]  # y = 1..15 (境界 y=0,16 を除く)
    return int(np.sum(v_internal == 0) + np.sum(h_internal == 0))


def verify_one(seed, v_walls, h_walls):
    result = {"seed": int(seed)}

    # (a) 連結性
    reachable = bfs_reachable(v_walls, h_walls, (0, 0))
    result["connectivity_ok"] = bool(len(reachable) == 256)
    result["reachable_cells"] = len(reachable)

    # (b) 中央2x2
    # 注意: numpy の bool_ 同士を "+" で連結すると算術和ではなく論理 OR に
    # なってしまう (numpy の既知の挙動)。ここでは int() で個別に変換してから
    # 加算し、正しい枚数を集計する。
    # Note: chaining numpy.bool_ values with "+" performs logical OR, not
    # arithmetic addition. Cast each term to int individually before summing
    # to get the correct count.
    center_walls_present = (
        int(v_walls[8, 7] == 1)
        + int(v_walls[8, 8] == 1)
        + int(h_walls[7, 8] == 1)
        + int(h_walls[8, 8] == 1)
    )
    opening = goal_opening_count(v_walls, h_walls)
    result["center_ok"] = bool(center_walls_present == 0 and opening >= 1)
    result["center_walls_present"] = center_walls_present
    result["goal_openings"] = opening

    # (c) スタート規定
    result["start_ok"] = bool(
        v_walls[1, 0] == 1
        and h_walls[0, 0] == 1
        and v_walls[0, 0] == 1
        and h_walls[0, 1] == 0
    )

    # (d) 孤立柱ゼロ (中央柱を除く全柱 >=1枚、中央柱は0枚)
    isolated_posts = []
    for px in range(17):
        for py in range(17):
            if px == 8 and py == 8:
                continue
            if post_connection_count(v_walls, h_walls, px, py) == 0:
                isolated_posts.append([px, py])
    center_post_connections = post_connection_count(v_walls, h_walls, 8, 8)
    result["isolated_posts_ok"] = bool(
        len(isolated_posts) == 0 and center_post_connections == 0
    )
    result["isolated_posts"] = isolated_posts
    result["center_post_connections"] = center_post_connections

    # (e) 再現性
    v_regen, h_regen = EvalMazeGenerator.generate(seed)
    result["reproducible_ok"] = bool(
        np.array_equal(v_walls, v_regen) and np.array_equal(h_walls, h_regen)
    )

    # 記録項目 (合否判定なし)
    result["internal_open_passages"] = internal_open_passage_count(v_walls, h_walls)
    result["start_to_goal_min_dist"] = bfs_distance(v_walls, h_walls, (0, 0), GOAL_CELLS)

    result["all_pass"] = bool(
        result["connectivity_ok"]
        and result["center_ok"]
        and result["start_ok"]
        and result["isolated_posts_ok"]
        and result["reproducible_ok"]
    )
    return result


def _mark(ok: bool) -> str:
    return "○" if ok else "×"


def render_log_section(results, summary) -> str:
    """VERIFICATION_LOG.md 「2. 案A適用後の検証」セクションの本文を
    検証結果 (results, summary) から機械的に組み立てる。
    Build the "2. Post-Plan-A verification" section body mechanically from
    the verification results/summary.
    """
    now = datetime.datetime.now().isoformat(timespec="seconds")
    seeds = [r["seed"] for r in results]
    n_total = summary["total"]

    lines = []
    lines.append("## 2. 案A適用後の検証")
    lines.append("")
    lines.append(
        "verify_eval_mazes.py --write-log による自動生成"
        "(手動編集しないこと。再実行すれば上書きされる)。"
    )
    lines.append("")
    lines.append(f"- 実行日時: {now}")
    lines.append(f"- 対象 seed: {seeds[0]}-{seeds[-1]} ({n_total}面)")
    lines.append(f"- 総合判定: **{summary['pass']}/{n_total} 合格**")
    lines.append("")
    lines.append("### 項目別合否 (5項目)")
    lines.append("")
    lines.append(f"- (a) 連結性 (全256セル到達可能): {summary['connectivity_pass']}/{n_total}")
    lines.append(f"- (b) 中央2x2ゴール開放 (内壁0枚 かつ 開口数>=1): {summary['center_pass']}/{n_total}")
    lines.append(f"- (c) スタート規定 (北開放・東壁・外周閉鎖): {summary['start_pass']}/{n_total}")
    lines.append(f"- (d) 孤立柱ゼロ (中央柱以外は壁>=1枚、中央柱は壁0枚): {summary['isolated_posts_pass']}/{n_total}")
    lines.append(f"- (e) 再現性 (同seed再生成でnpzと完全一致): {summary['reproducible_pass']}/{n_total}")
    lines.append("")
    lines.append("### 記録項目 (合否判定なし)")
    lines.append("")
    lines.append(
        "- スタート→ゴール最短セル距離 (BFS, ゴール4セルへの最小): "
        f"min={summary['start_to_goal_dist_min']}, "
        f"median={summary['start_to_goal_dist_median']}, "
        f"max={summary['start_to_goal_dist_max']}"
    )
    lines.append("")
    lines.append("### 迷路ごとの検証結果表")
    lines.append("")
    lines.append(
        "| seed | (a)連結性 | (b)中央2x2 | (c)スタート規定 | (d)孤立柱ゼロ | "
        "(e)再現性 | 最短距離 | ゴール開口数 | 内部開通路数 |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for r in results:
        lines.append(
            f"| {r['seed']} | {_mark(r['connectivity_ok'])} | {_mark(r['center_ok'])} | "
            f"{_mark(r['start_ok'])} | {_mark(r['isolated_posts_ok'])} | "
            f"{_mark(r['reproducible_ok'])} | {r['start_to_goal_min_dist']} | "
            f"{r['goal_openings']} | {r['internal_open_passages']} |"
        )
    lines.append("")
    return "\n".join(lines)


def write_log(results, summary, log_path: str = LOG_PATH) -> None:
    """VERIFICATION_LOG.md の「2. 案A適用後の検証」セクションを
    マーカー間で置換 (存在しなければ末尾に追記) する。
    Replace the "2. Post-Plan-A verification" section between markers
    in VERIFICATION_LOG.md (append at the end if the markers are absent).
    """
    section_body = render_log_section(results, summary)
    block = f"{LOG_SECTION_START}\n{section_body}\n{LOG_SECTION_END}\n"

    content = ""
    if os.path.exists(log_path):
        with open(log_path, "r") as f:
            content = f.read()

    if LOG_SECTION_START in content and LOG_SECTION_END in content:
        pre, _, rest = content.partition(LOG_SECTION_START)
        _, _, post = rest.partition(LOG_SECTION_END)
        post = post.lstrip("\n")
        new_content = pre.rstrip("\n") + "\n\n" + block
        if post:
            new_content += "\n" + post
    else:
        sep = "\n" if content and not content.endswith("\n\n") else ""
        new_content = content + sep + ("\n" if content and not content.endswith("\n") else "") + block

    with open(log_path, "w") as f:
        f.write(new_content)
    print(f"[verify_eval_mazes] updated {log_path} (section: 案A適用後の検証)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write-log",
        action="store_true",
        help="VERIFICATION_LOG.md の「2. 案A適用後の検証」セクションを機械的に書き出す",
    )
    parser.add_argument(
        "--log-path",
        default=LOG_PATH,
        help="書き出し先のパス (デフォルト: competition/VERIFICATION_LOG.md)",
    )
    args = parser.parse_args()

    npz_files = sorted(glob.glob(os.path.join(MAZE_DIR, "maze_*.npz")))
    if not npz_files:
        print(f"[verify_eval_mazes] npzファイルが見つかりません: {MAZE_DIR}")
        return 1

    results = []
    for path in npz_files:
        data = np.load(path)
        seed = int(data["seed"])
        v_walls = data["v_walls"]
        h_walls = data["h_walls"]
        r = verify_one(seed, v_walls, h_walls)
        r["file"] = os.path.basename(path)
        results.append(r)

    results.sort(key=lambda r: r["seed"])

    header = (
        f"{'seed':>6} {'conn':>6} {'center':>7} {'start':>6} {'iso':>6} "
        f"{'repro':>6} {'dist':>5} {'gopen':>6} {'passages':>9}"
    )
    print(header)
    print("-" * len(header))
    for r in results:
        print(
            f"{r['seed']:>6} {str(r['connectivity_ok']):>6} {str(r['center_ok']):>7} "
            f"{str(r['start_ok']):>6} {str(r['isolated_posts_ok']):>6} "
            f"{str(r['reproducible_ok']):>6} {str(r['start_to_goal_min_dist']):>5} "
            f"{r['goal_openings']:>6} {r['internal_open_passages']:>9}"
        )

    n_total = len(results)
    n_pass = sum(1 for r in results if r["all_pass"])
    dists = [r["start_to_goal_min_dist"] for r in results if r["start_to_goal_min_dist"] is not None]

    summary = {
        "total": n_total,
        "pass": n_pass,
        "fail": n_total - n_pass,
        "connectivity_pass": sum(1 for r in results if r["connectivity_ok"]),
        "center_pass": sum(1 for r in results if r["center_ok"]),
        "start_pass": sum(1 for r in results if r["start_ok"]),
        "isolated_posts_pass": sum(1 for r in results if r["isolated_posts_ok"]),
        "reproducible_pass": sum(1 for r in results if r["reproducible_ok"]),
        "start_to_goal_dist_min": min(dists) if dists else None,
        "start_to_goal_dist_median": float(np.median(dists)) if dists else None,
        "start_to_goal_dist_max": max(dists) if dists else None,
    }

    print()
    print(f"合格: {n_pass}/{n_total}")
    print(
        "内訳: "
        f"連結性 {summary['connectivity_pass']}/{n_total}, "
        f"中央2x2 {summary['center_pass']}/{n_total}, "
        f"スタート規定 {summary['start_pass']}/{n_total}, "
        f"孤立柱ゼロ {summary['isolated_posts_pass']}/{n_total}, "
        f"再現性 {summary['reproducible_pass']}/{n_total}"
    )
    if dists:
        print(
            "最短セル距離: "
            f"min={summary['start_to_goal_dist_min']}, "
            f"median={summary['start_to_goal_dist_median']}, "
            f"max={summary['start_to_goal_dist_max']}"
        )

    report = {"summary": summary, "results": results}
    report_path = os.path.join(MAZE_DIR, "verification_report.json")
    with open(report_path, "w") as f:
        json.dump(report, f, indent=2, ensure_ascii=False)
    print(f"\n[verify_eval_mazes] saved {report_path}")

    if args.write_log:
        write_log(results, summary, args.log_path)

    return 0 if n_pass == n_total else 1


if __name__ == "__main__":
    sys.exit(main())
