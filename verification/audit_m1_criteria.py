"""M1 の判定基準まわりの「導出」を、仕様書の定数だけから独立に再導出する。

作成: 2026-08-11 准教授セッション（独立検証担当）
教授指示（任務: 学生B 側の主要数値の独立再計算）のうち、**導出の監査**にあたる部分。

独立性:
  - 入力は `docs/ROBOT_SPEC.md` §3・§4 と `docs/MODEL_VERIFICATION_PLAN.md` §4.2 の
    「定数」のみ。**`research_notes/scripts/check_*.py` は読んでいない。**
  - 各式は条文の記述（例:「車輪ジョイント（ロータ+車輪）の時定数」）から自分で立てた。

注意: 本スクリプトは**走行データを使わない**。符号反転・HF比・RMS 電流の
      「実測値」の再計算には方策の再実行が要り、本スクリプトの範囲外である。
"""

import math

# ---------------------------------------------------------------- 仕様書の定数
# 出典: docs/ROBOT_SPEC.md §4 表（FAULHABER 1717T003SR、減速比 N=5）
N        = 5.0        # 減速比 [-]
R        = 1.07       # 巻線抵抗 [Ω]
K_t      = 1.98e-3    # トルク定数 [N·m/A]
K_e      = 1.98e-3    # 逆起電力定数 [V·s/rad]（カタログ換算 1.977e-3、丸め差のみ）
b        = 2.0e-6     # 車輪軸粘性 [N·m·s/rad]
J_rotor  = 0.59e-7    # ロータ慣性 0.59 g·cm² = 5.9e-8 kg·m²
TAU_CONT = 1.16e-3    # 連続定格トルク（モータ軸）[N·m]（ROBOT_SPEC §3 カタログ照合 項目 10）
m_wheel  = 0.005      # 車輪質量 [kg]（v2。MODEL_VERIFICATION §2.1 C1）
r_wheel  = 0.0135     # 車輪半径 [m]（同 C4 の J=4.55625e-6 / m=0.05 から逆算しても一致）
DT       = 0.01       # 制御周期 [s]（100 Hz）
F_NYQ    = 1.0 / (2 * DT)   # 制御周期の Nyquist [Hz]

print("=" * 78)
print("M1 判定基準の導出監査 — 仕様書の定数のみから独立に再導出")
print("=" * 78)

# ---------------------------------------------------------------- 1. 連続定格電流
print("\n[1] 連続定格電流 I_cont")
I_cont = TAU_CONT / K_t
print(f"    I_cont = 連続定格トルク / K_t = {TAU_CONT:.3e} / {K_t:.3e} = {I_cont:.4f} A")
print(f"    → 引き継がれている値 0.586 A と {'一致' if abs(I_cont-0.586)<5e-4 else '不一致'}")
print("    注: 連続定格トルクは**モータ軸**の値なので、減速比 N で割らない。")
print("        車輪軸トルクを使うなら N で割る必要があり、5 倍ずれる。ここは正しい。")

# ---------------------------------------------------------------- 2. 機械時定数（カタログ照合）
print("\n[2] モータ単体の機械時定数 T_m（仕様書の整合検算の再現）")
T_m = R * J_rotor / (K_t * K_e)
print(f"    T_m = R·J_rotor/(K_t·K_e) = {R}·{J_rotor:.3e}/({K_t:.3e})² = {T_m*1e3:.2f} ms")
print(f"    → カタログ値 16 ms と{'一致' if abs(T_m*1e3-16)<0.5 else '不一致'}（仕様書 §7 の整合検算 2 件目）")

# ---------------------------------------------------------------- 3. 車輪ジョイントの時定数と必達線
print("\n[3] 車輪ジョイント（ロータ+車輪）の時定数 τ_wheel と、符号反転の必達線")
J_arm = N**2 * J_rotor                  # ロータ慣性の車輪軸換算（armature）
J_w   = 0.5 * m_wheel * r_wheel**2      # 車輪の慣性（一様円板）
J_tot = J_arm + J_w
c_emf = N**2 * K_t * K_e / R            # 逆起電力による粘性（車輪軸換算）
c_tot = c_emf + b
tau_w = J_tot / c_tot
f_c   = 1.0 / (2 * math.pi * tau_w)
flip_line = 2.0 * f_c                   # 方形波 1 周期あたり符号反転 2 回

print(f"    armature   N²·J_rotor = {J_arm:.4e} kg·m²  （仕様書の armature 1.475e-6 と照合）")
print(f"    車輪慣性   ½·m·r²     = {J_w:.4e} kg·m²")
print(f"    合計       J_tot      = {J_tot:.4e} kg·m²")
print(f"    逆起電力粘性 N²KtKe/R = {c_emf:.4e} N·m·s/rad （biasprm[2] −9.16e-5 と照合）")
print(f"    軸受粘性 b            = {b:.1e}")
print(f"    → τ_wheel = J_tot/(c_emf+b) = {tau_w*1e3:.2f} ms")
print(f"       f_c     = 1/(2π·τ)       = {f_c:.3f} Hz")
print(f"       必達線  = 2·f_c          = {flip_line:.2f} 回/s")
print(f"    → 引き継がれている 15.4 回/s と {'一致' if abs(flip_line-15.4)<0.15 else '不一致'}")
print("    注: 反転率が 2·f なのは、方形波が 1 周期に 2 回ゼロを跨ぐため。")

# 感度: b を落とすと / 車輪慣性を落とすとどうなるか（式の同定が正しいことの傍証）
tau_no_b = J_tot / c_emf
tau_no_w = J_arm / c_tot
print(f"    感度: b を無視 → τ={tau_no_b*1e3:.2f} ms（反転 {2/(2*math.pi*tau_no_b):.1f} 回/s）"
      f" ／ 車輪慣性を無視 → τ={tau_no_w*1e3:.2f} ms（{2/(2*math.pi*tau_no_w):.1f} 回/s）")
print("       → **b と車輪慣性を両方入れたときだけ 20.6 ms / 15.4 回/s になる。**式の同定は一意。")

# ---------------------------------------------------------------- 4. 乱数方策の理論反転率
print("\n[4] 乱数方策の符号反転率（理論値）")
print(f"    平均 0 の対称分布から独立に引くと、隣接ステップで符号が変わる確率はちょうど 1/2。")
print(f"    → 100 Hz なら {1/DT:.0f} 遷移/s × 1/2 = {0.5/DT:.0f} 回/s。**σ に依存しない。**")
print(f"    引き継がれている「理論値 50 回/s」と一致。")
print(f"    含意: exp_005 の 75.6 回/s は理論値 50 を上回る ＝ 独立サンプリングでは到達できない。")
print(f"          方策が時間的に負の相関を持つ（能動的に交互に振っている）ことを意味する。")

# ---------------------------------------------------------------- 5. HF比の α と理論最悪値
print("\n[5] 高周波エネルギー比の α と理論最悪値")
alpha = math.exp(-DT / tau_w)
print(f"    α = exp(−Δt/τ_wheel) = exp(−{DT}/{tau_w:.5f}) = {alpha:.4f}")
print(f"    → 引き継がれている 0.616 と {'一致' if abs(alpha-0.616)<2e-3 else '不一致'}")
# 全振幅で Nyquist 交番する方形波に対する定常応答
A = (1 - alpha) / (1 + alpha)
worst = 1 - A
print(f"    理論最悪値の導出: a_t が ±1 を毎ステップ交番するとき、")
print(f"      ā は ±A に収束する（A = (1−α)/(1+α) = {A:.4f}）")
print(f"      よって |a − ā| = 1 − A = {worst:.4f}")
print(f"    → 引き継がれている 0.762 と {'一致' if abs(worst-0.762)<1e-3 else '不一致'}")

# ---------------------------------------------------------------- 6. 必要な熱時定数の式
print("\n[6] 必要な熱時定数 τ_th の式（条件式を τ について解く）")
print("    一次遅れの温度上昇: ΔT(t)/ΔT_cont = (I_rms/I_cont)²·(1 − e^(−t/τ)) ≤ 1")
print("    k ≡ (I_rms/I_cont)² と置くと  1 − e^(−t/τ) ≤ 1/k")
print("      → e^(−t/τ) ≥ 1 − 1/k  →  −t/τ ≥ ln(1 − 1/k)  →  **τ ≥ −t / ln(1 − 1/k)**")
print("    （k ≤ 1 なら右辺が定義されない ＝ 定格以下なので時間によらず焼けない）")


def tau_required(ratio: float, t: float):
    k = ratio ** 2
    if k <= 1.0:
        return None
    return -t / math.log(1.0 - 1.0 / k)


print("\n    引き継がれている表の再現（定格比と走行時間から τ_th を再計算）:")
print(f"      {'定格比':>8}{'走行[s]':>9}{'再計算 τ_th[s]':>16}{'引き継ぎ値':>12}")
for ratio, t, quoted in [(3.56, 2.67, 32.6), (1.76, 2.45, 6.3), (1.38, 2.61, 3.5)]:
    tr = tau_required(ratio, t)
    ok = "一致" if tr is not None and abs(tr - quoted) < 0.15 else "不一致"
    print(f"      {ratio:>8.2f}{t:>9.2f}{tr:>16.2f}{quoted:>10.1f}  {ok}")
print("    → 式は正しい。3 点とも再現する。")

