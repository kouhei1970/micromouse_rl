#!/usr/bin/env python3
"""exp_005 の報酬が、廊下からマイクロマウス迷路へスケールしたときどうなるか。

作成: 2026-08-11 准教授セッション（独立検証担当）
文脈: 留保 2「報酬の滞留局所解」の解消は**廊下コースでの 3/3 seed**を根拠にしている。
      M2 以降（迷路）で同じ罠が復活しないと言えるかを、割引後総収益の計算で確かめる。

報酬（exp_005、`docs/RESEARCH_PLAN.md` §9-3 と exp_005 card §2）:
    r_t = γ·Φ'(s_{t+1}) − Φ'(s_t) − t_p     Φ' = D₀ − D  [m]
    終端: ゴール +1.0 / 衝突 −1.0
"""

import math

GAMMA = 0.995
TP = 0.001


def ret(d0_m: float, phi_end_m: float, T: int, terminal: float) -> float:
    """開始状態（Φ'=0）からの割引後総収益。

    整形項は telescoping して γ^T·Φ'_T − Φ'_0。
    時間罰は等比和。終端報酬は γ^(T−1) で割り引く。
    """
    gT = GAMMA ** T
    shaping = gT * phi_end_m                       # Φ'_0 = 0
    timepen = -TP * (1 - gT) / (1 - GAMMA)
    term = (GAMMA ** (T - 1)) * terminal if T > 0 else terminal
    return shaping + timepen + term


print("=" * 78)
print("exp_005 の報酬を、廊下スケールと迷路スケールで比べる")
print("=" * 78)
print(f"γ = {GAMMA}  →  実効地平 1/(1−γ) = {1/(1-GAMMA):.0f} ステップ = {1/(1-GAMMA)*0.01:.1f} 秒")

print("\n[検算] 廊下（D₀ = 2.52 m。exp_005 card §2 の表を再現できるか）")
g = ret(2.52, 2.52, 300, +1.0)
c = ret(2.52, 1.60, 100, -1.0)
d = ret(2.52, 0.0, 372, 0.0)
print(f"    ゴール(300 歩) {g:+.3f}   衝突(1.6 m・100 歩) {c:+.3f}   滞留(時間切れ) {d:+.3f}")
print(f"    card の値       +0.627                 +0.285                  −0.200")
print(f"    → 再現する（規約差による誤差 {abs(g-0.627):.3f} 以内）。以下の外挿に同じ式を使う")

print("\n[本題] 迷路スケールへ外挿する")
print("    D₀: 16x16 の真の最短距離 75 区画 × 0.18 m = 13.5 m（評価帯の中央値 74.5 区画）")
print("    ゴール到達までの歩数: 1.0 m/s で走ると 13.5 s = 1350 歩")

rows = [
    ("廊下（現行 M1）", 2.52, 300, 372),
    ("6x6 迷路（M2 想定・D₀≈20 区画）", 20 * 0.18, int(20 * 0.18 / 1.0 * 100), 2000),
    ("16x16 迷路（M3 想定・D₀≈75 区画）", 75 * 0.18, int(75 * 0.18 / 1.0 * 100), 42000),
]
print(f"\n    {'条件':<34}{'ゴール':>10}{'滞留':>10}{'差':>10}{'γ^T':>10}")
for name, d0, Tg, Td in rows:
    gg = ret(d0, d0, Tg, +1.0)
    dd = ret(d0, 0.0, Td, 0.0)
    print(f"    {name:<34}{gg:>+10.3f}{dd:>+10.3f}{gg-dd:>+10.3f}{GAMMA**Tg:>10.5f}")

print("\n[比較] 差がどれだけ縮むか")
g_cor = ret(2.52, 2.52, 300, +1.0) - ret(2.52, 0.0, 372, 0.0)
g_maze = ret(13.5, 13.5, 1350, +1.0) - ret(13.5, 0.0, 42000, 0.0)
print(f"    廊下   ゴール − 滞留 = {g_cor:+.3f}")
print(f"    16x16  ゴール − 滞留 = {g_maze:+.3f}")
print(f"    → **{g_cor/g_maze:.0f} 分の 1 に縮む**")
print(f"\n    参考: exp_003 で実際に滞留解へ落ちたときの差は **+0.267**（Φ=−D の旧報酬）。")
print(f"          16x16 での差 {g_maze:+.3f} は、その **{0.267/g_maze:.0f} 分の 1** である。")

print("\n[順序の確認] 16x16 で ゴール > 滞留 > 衝突 の順序は保たれるか")
gg = ret(13.5, 13.5, 1350, +1.0)
dd = ret(13.5, 0.0, 42000, 0.0)
cc_near = ret(13.5, 0.18, 10, -1.0)          # 出だしで衝突
cc_far = ret(13.5, 12.0, 1200, -1.0)         # ゴール直前で衝突
print(f"    ゴール {gg:+.3f} > 滞留 {dd:+.3f} > 衝突(出だし) {cc_near:+.3f}")
print(f"    ゴール直前で衝突 {cc_far:+.3f}")
print(f"    → 順序自体は保たれる。**壊れるのは順序ではなく余裕**")

print("\n[機構] なぜ縮むか")
print(f"    ゴール報酬 +1.0 と整形の総和 γ^T·D₀ は、どちらも γ^T で割り引かれる。")
print(f"    廊下は T=300 歩で γ^T = {GAMMA**300:.3f}（実効地平 200 歩と同程度）。")
print(f"    16x16 は T=1350 歩で γ^T = {GAMMA**1350:.5f}（実効地平の 6.75 倍）。")
print(f"    → **ゴールに到達しても、その価値は開始時点でほぼゼロに割り引かれている。**")
print(f"    一方 滞留の −0.2 は t_p の等比和の漸近値なので、エピソード長によらずほぼ一定。")
print(f"    **ゴール側だけが縮み、滞留側は縮まない。**")

print("\n" + "=" * 78)
print("留保（本スクリプトの限界）")
