print("    `experiments/n1_evidence_audit.md` D 節。学習は未実施 ＝ n=0）。")
print("    本計算は **exp_005 の報酬をそのまま迷路へ持っていった場合** の話である。")
print("  - 歩数の見積り（1.0 m/s）と時間切れの歩数は仮定。γ^T が支配的なので")
print("    見積りが 2 倍ずれても結論の向きは変わらない（下記）。")
